#!/bin/sh
# 터미널이 질의에 답하는가 — 커서 위치를 묻고 그 답을 읽는다(TQ-M1).
#
# 게이트가 이 파일을 /usr/bin/tq-probe로 게스트에 싣고 이름으로 친다.
# 커서 위치 질의(`ESC[6n`)가 자리인 이유는 fzf가 `--height`일 때 그것을 묻고
# 답이 올 때까지 그리지 않기 때문이다 — 답이 없으면 Ctrl+R이 첫 누름에
# 멈춘다(ST-M3 실측).
#
# 질의 바이트를 게이트가 타이핑으로 만들 수 없다. `printf '\033[6n'`을
# `type_keys`로 치면 이스케이프가 fish → bash → printf 층에서 죽어 리터럴
# `033[6n`이 나간다(화면에 그대로 찍히는 것으로 확인했다). 그래서 ESC가 든
# 스크립트를 initrd에 실어 그 경로를 치게 한다 — dhcpcd hook을 싣는 것과
# 같은 방식이다.
#
# 묻기와 읽기가 한 프로세스 안에 있어야 한다. 답은 pty의 입력이고, 그 사이에
# 프롬프트로 돌아온 셸의 라인 편집기가 먼저 가져가면 0바이트가 된다 —
# 물어보는 프로세스가 끝나고 다른 프로세스가 읽는 모양이 정확히 그렇게 된다.
#
# 판정은 길이다. 답이 오면 `len6`(CPR은 `ESC[행;열R` 6바이트), 안 오면
# `len0`이다. 정확한 문자열을 안 박는 것은 포맷이 vendored ghostty의 몫이라
# 그것을 박으면 우리가 아니라 그 코드를 검사하게 되기 때문이다(design 결정 5).
#
# `read -n`/`-t`는 bash의 것이다. 이 기계의 /bin/sh가 bash라서 되는 것이고
# (make_initrd.sh가 그렇게 건다), #!/bin/sh인 것은 그것이 이 게스트의
# "스크립트"라는 뜻이기 때문이다.
printf '\033[6n'
read -n 20 -t 2 r
printf 'len%d\n' "${#r}"
